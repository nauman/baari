"""Generate a self-contained Kuickr deployment from the public site sources.

The command ledger stays generated by Baari's release runner. No command or
capability inventory is authored here. Output is a deployment artifact.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = (ROOT / 'landing.html').read_text()
ledger = json.loads((ROOT / 'commands.json').read_text())
assert ledger['schema'] == 'baari-command-ledger/v1'
# Hydrate the first paint from the same release ledger; no JS-only version badge.
assert re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+(?:[-+][0-9A-Za-z.-]+)?', ledger['version'])
source = re.sub(r'(<span data-release-version>)[^<]*(</span>)', lambda m: m[1] + 'v' + ledger['version'] + m[2], source)
source = re.sub(r'(data-release-link href=")[^"]*(")', lambda m: m[1] + 'https://github.com/nauman/baari/releases/tag/v' + ledger['version'] + m[2], source)
start = 'fetch("commands.json", { cache: "no-cache" }).then(function (response) {'
end = '    }).then(function (data) {'
a = source.index(start)
b = source.index(end, a)
source = source[:a] + 'Promise.resolve(JSON.parse(document.getElementById("release-command-ledger").textContent)).then(function (data) {' + source[b+len(end):]
encoded = json.dumps(ledger).replace('<', '\\u003c')
source = source.replace('</head>', '<script id="release-command-ledger" type="application/json">' + encoded + '</script></head>')
# Frozen Nodepad token snapshot was obtained from the registered design system.
tokens = (ROOT / 'assets/nodepad-tokens.css').read_text()
source = source.replace('<html lang="en">', '<html lang="en" class="np-tokens np-wash" data-theme="light">')
source = source.replace('<style>\n:root', '<style>' + tokens + '</style>\n<style>\n:root', 1)
# Preserve the existing layout; bind its colour/typography aliases to Nodepad.
source = source.replace('</head>', '''<style>
:root,[data-theme="light"],[data-theme="dark"]{--sans:var(--np-sans);--mono:var(--np-mono);--bg:var(--np-wash);--surface:var(--np-bg);--surface-deep:var(--np-paper-deep);--ink:var(--np-ink-runtime);--text:var(--np-text);--muted:var(--np-muted);--line:var(--np-line);--line-soft:var(--np-line-soft);--amber:var(--np-amber);--amber-text:var(--np-accent-text,var(--np-amber-text));--highlight:var(--np-highlight)}
</style></head>''')
# Public deployment assets never depend on private folder traversal.
base = 'https://nauman.github.io/baari/'
for name in ['favicon.svg', 'apple-touch-icon.png', 'og-image.png', 'install.sh']:
    source = source.replace('href="' + name + '"', 'href="' + base + name + '"')
source = source.replace('href="walkthrough/README.md"', 'href="https://kuickr.co/spaces/dev-docs-74/baari/walkthrough.md"')
output = ROOT / '.kuickr-build'
output.mkdir(exist_ok=True)
(output / 'index.html').write_text(source)
print(output / 'index.html')

narration = json.loads((ROOT / 'walkthrough/narration.json').read_text())
intro = (ROOT / 'walkthrough/README.md').read_text()
intro = intro.replace('[narration.json](narration.json)', '[narration.json](https://github.com/nauman/baari/blob/main/walkthrough/narration.json)')
heading, _, rest = intro.partition('\n')
walkthrough = heading + '\n\n{{embed:youtube:OsDPxOch6O8}}\n\n' + rest + '\n\n'
walkthrough += '[Download the MP4](walkthrough.media/baari-workflow.mp4) · [Captions](walkthrough.media/baari-workflow.srt)\n\n'
duration = round(sum(clip['duration'] for clip in narration), 2)
walkthrough += f'{duration:g} seconds · 1920 × 1080 · AI-generated Aiden voice. Sentence captions use proportional timing, not forced alignment.\n\nApproved by Nauman on 17 November 2026.\n\n## Transcript\n\n'
walkthrough += '\n\n'.join('### ' + c['title'] + '\n\n' + c['text'].replace('baari dot quicker dot co', 'baari.kuickr.co') for c in narration) + '\n'
(output / 'walkthrough.md').write_text(walkthrough)

# Social drafts are maintained in Distribution, never regenerated here.
(output / "launch.md").unlink(missing_ok=True)
